// 阿强：勤快、省、从不想别的出路。第一版只是认识他。
export function qiangLine(month, s) {
  if (s.machines > 0) return '听说你在店门口摆了台机器？那玩意儿靠谱吗……我还是觉得钱放银行最踏实。';
  if (s.classes > 0 && s.classes < 8) return '下了班还去上课？我可不行，一天两份工，回去倒头就睡。';
  return [
    '新来的吧？我叫阿强，在后厨。这儿活不难，就是站得腿疼。',
    '我一天打两份工，一分钱都不乱花。再攒几年，说不定能付个首付。',
    '最近菜又涨价了，工资倒是没动。没事，多加几个班就有了。',
    '我妈说了，老老实实干活，日子总会好的。',
  ][Math.min(3, month - 1)];
}

